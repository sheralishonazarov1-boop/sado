export function getTranslation(locale: Locale, key: string): string {
  const currentLocale = locale || 'uz';
  const val = (i18nStrings[currentLocale] as any)[key] || (i18nStrings['uz'] as any)[key];
  return val || key;
}

export function getNestedTranslation(locale: Locale, parentKey: string, childKey: string): string {
  const currentLocale = locale || 'uz';
  const parentObj = (i18nStrings[currentLocale] as any)[parentKey] || (i18nStrings['uz'] as any)[parentKey];
  if (parentObj && typeof parentObj === 'object') {
    return parentObj[childKey] || (i18nStrings['uz'] as any)[parentKey]?.[childKey] || childKey;
  }
  return childKey;
}
